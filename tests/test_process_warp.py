"""Print warp: the shrinkage profile, frames, slicer profiles and the CalculiX solve against Timoshenko's bimetal."""
import json
import zipfile

import numpy as np
import pytest

from conftest import needs_ccx
from wobbl.process import warp as W
from wobbl.process.data import RAMP_HEIGHT
from wobbl.process.slicer import read_profile


def test_a_linear_ramp_bends_a_plate_to_its_slope():
    # shrinkage rising linearly through the whole height bends a free plate to exactly that slope
    eps = 2e-3
    k = W.plate_curvature(5.0, lambda z: W.shrinkage_profile(z, eps))
    assert k == pytest.approx(eps / RAMP_HEIGHT, rel=1e-4)
    # a uniform shrinkage does not bend it at all
    assert W.plate_curvature(5.0, lambda z: np.full_like(z, eps)) == pytest.approx(0.0, abs=1e-12)


def test_timoshenko_reduces_to_the_beam_formula_for_equal_layers():
    # equal stiffness: kappa = 6 d_eps t1 t2 / h^3
    assert W.timoshenko_bimetal(1.0, 3.0, 2000, 2000, 1e-3) == pytest.approx(6e-3 * 3 / 64)


@pytest.mark.parametrize("d", ["z", "-y", "x", "0,0.6,0.8"])
def test_the_print_direction_becomes_up(d):
    v = W.build_direction(d)
    R = W.to_build_frame(v)
    assert np.allclose(R @ v, [0, 0, 1]) and np.allclose(R @ R.T, np.eye(3))


def test_cura_orca_and_prusa_profiles(tmp_path):
    cura = tmp_path / "abs_fine.inst.cfg"
    cura.write_text("[general]\nversion = 4\n[values]\nlayer_height = 0.15\nmaterial_bed_temperature = 100\n"
                    "build_volume_temperature = 45\ninfill_sparse_density = 25\nwall_line_count = 3\n"
                    "adhesion_type = brim\nbrim_width = 6\n")
    p = read_profile(cura)
    assert (p["layer_height"], p["bed_C"], p["chamber_C"], p["infill"], p["walls"], p["brim_mm"]) == \
        (0.15, 100.0, 45.0, 0.25, 3.0, 6.0)
    assert p["adhesion"] == "brim" and p["slicer"] == "Cura" and p["sources"]["bed_C"].endswith("material_bed_temperature")
    orca = tmp_path / "creality.json"
    orca.write_text(json.dumps({"layer_height": "0.2", "hot_plate_temp": ["90"], "sparse_infill_density": "15%",
                                "wall_loops": "2", "filament_type": ["PETG"], "top_shell_layers": "4"}))
    q = read_profile(orca)
    assert (q["bed_C"], q["infill"], q["walls"], q["material"], q["top_layers"]) == (90.0, 0.15, 2.0, "petg", 4.0)
    project = tmp_path / "plate.3mf"
    with zipfile.ZipFile(project, "w") as z:
        z.writestr("Metadata/Slic3r_PE.config", "; generated by PrusaSlicer\nbed_temperature = 110\n"
                                                "fill_density = 20%\nperimeters = 4\nlayer_height = 0.25\n")
    r = read_profile(project)
    assert (r["bed_C"], r["infill"], r["walls"], r["layer_height"]) == (110.0, 0.2, 4.0, 0.25)


@needs_ccx
@pytest.mark.solver
def test_a_bonded_strip_curls_as_timoshenko_says(tmp_path):
    from wobbl.geometry.cad import prepare
    from wobbl.mesh.mesher import Sizing, build_mesh
    from wobbl.validation import geometry as G

    L, B, t1, t2, E1, E2, de = 100.0, 10.0, 2.0, 2.0, 2200.0, 1100.0, 1e-3

    def two(o):
        a = o.addBox(0, 0, 0, L, B, t2)
        b = o.addBox(0, 0, t2, L, B, t1)
        o.fragment([(3, a)], [(3, b)])

    mesh = build_mesh(prepare(G._session(tmp_path / "strip.step", two), tmp_path / "geo"), Sizing(h=2.0))
    top = mesh.X[mesh.tets[:, :4]].mean(axis=1)[:, 2] > t2
    ws = W.solve(mesh.X, mesh.tets, np.where(top, E1, E2), 0.35, np.full(len(mesh.X), de), tmp_path / "work",
                 alpha=np.where(top, 1.0, 0.0))
    kappa = W.bottom_curvature(mesh.X, ws)[0]
    assert kappa == pytest.approx(W.timoshenko_bimetal(t1, t2, E1, E2, de), rel=0.02)
    # the shrinkage loads balance themselves, so the bed carries no net force
    assert np.abs(ws.RF_bed[ws.bed].sum(0)).max() < 1e-3
    assert W.measure(mesh.X, ws)["flatness_mm"] == pytest.approx(kappa * (L * L + B * B) / 8, rel=0.1)
